const index = JSON.parse(
  fs.readFileSync(path.join(ROOT, "public/celebs/index.json"), "utf8"),
);
const known = new Set(index.map((row) => row.id));
const out = {};
const seen = new Set();
const missing = [];
const collisions = [];

for (const [family, ids] of Object.entries(SEED)) {
  for (const id of ids) {
    if (!known.has(id)) {
      missing.push(`${family}:${id}`);
      continue;
    }
    if (seen.has(id)) {
      collisions.push(id);
      continue;
    }
    seen.add(id);
    out[id] = family;
  }
}

const dest = path.join(ROOT, "public/celebs/appearance-families.json");
fs.writeFileSync(dest, `${JSON.stringify(out, null, 2)}\n`);
